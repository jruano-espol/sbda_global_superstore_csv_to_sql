        for row in rows:
            for name, value in row.fields.items():
                # Solo considerar atributos pertenecientes a esta entidad.
                belongs_to_customer = (entity_id == "Customer ID" and name in ("Customer Name", "Segment"))
                belongs_to_product = (entity_id == "Product ID" and name in ("Product Name", "Category", "Sub-Category"))
